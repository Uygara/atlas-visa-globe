#!/usr/bin/env node
// Monthly climate normals for the climate map: data/climate.js.
//
// Source: World Bank Climate Change Knowledge Portal (CCKP), ERA5 reanalysis
// 0.25°, 1991–2020 monthly climatology, one value per country (area average).
// Licence CC BY 4.0 (World Bank) on ERA5 data (Copernicus licence, free for
// commercial use with attribution). The attribution is shown on the page.
//
// Normals do not change from day to day: run this by hand when the portal
// publishes a new period, not in the daily workflow.
//   node backend/fetch-climate.js
//
// Values stored per country (ISO2), 12 months each, January first:
//   hi = mean daily maximum temperature (°C, rounded)
//   lo = mean daily minimum temperature (°C, rounded)
//   pr = mean monthly precipitation (mm, rounded)

const fs = require("fs");
const path = require("path");

const BASE = "https://cckpapi.worldbank.org/cckp/v1/era5-x0.25_climatology_{v}_climatology_monthly_1991-2020_mean_historical_era5_x0.25_mean/all_countries?_format=json";
const CODES = "https://unpkg.com/i18n-iso-countries@7.11.0/codes.json"; // [iso2, iso3, numeric, …]
const OUT = path.join(__dirname, "..", "data", "climate.js");

async function getJson(url) {
  const r = await fetch(url, { headers: { "User-Agent": "travelnow-climate/1.0" } });
  if (!r.ok) throw new Error(url + " → HTTP " + r.status);
  return r.json();
}

(async () => {
  const codes = await getJson(CODES);
  const toIso2 = { XKX: "XK", KSV: "XK" };
  for (const [iso2, iso3] of codes) toIso2[iso3] = iso2;

  const vars = { hi: "tasmax", lo: "tasmin", pr: "pr" };
  const raw = {};
  for (const [k, v] of Object.entries(vars)) raw[k] = (await getJson(BASE.replace("{v}", v))).data;

  const countries = {};
  const skipped = [];
  for (const iso3 of Object.keys(raw.hi).sort()) {
    const iso2 = toIso2[iso3];
    if (!iso2) { skipped.push(iso3); continue; }
    const row = {};
    let ok = true;
    for (const k of Object.keys(vars)) {
      const m = raw[k][iso3];
      if (!m) { ok = false; break; }
      const vals = Object.keys(m).sort().map((key) => m[key]);
      if (vals.length !== 12 || vals.some((x) => typeof x !== "number" || !isFinite(x))) { ok = false; break; }
      row[k] = vals.map((x) => Math.round(x));
    }
    if (ok) countries[iso2] = row;
    else skipped.push(iso3);
  }

  const out = {
    period: "1991–2020",
    source: "World Bank Climate Change Knowledge Portal (ERA5, 1991–2020)",
    sourceUrl: "https://climateknowledgeportal.worldbank.org/",
    licence: "CC BY 4.0",
    generated: new Date().toISOString().slice(0, 10),
    countries,
  };
  const body = "// Generated by backend/fetch-climate.js. Do not edit by hand.\n" +
    "// Monthly climate normals per country (area average), January first: hi/lo °C, pr mm.\n" +
    "window.CLIMATE = " + JSON.stringify(out) + ";\n";
  fs.writeFileSync(OUT, body);
  console.log("wrote", OUT, Object.keys(countries).length, "countries; skipped", skipped.join(",") || "none");
})().catch((e) => { console.error(e); process.exit(1); });
