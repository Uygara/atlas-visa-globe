// fetch-airports.js — IATA airport code → country and city, for the transit map's
// "check a connection" box (type IST → FRA → JFK and see the transit rule for
// Germany).
//
// Source: OurAirports (public domain) https://github.com/davidmegginson/ourairports-data
// Kept: airports with scheduled passenger service and an IATA code — about 3,900
// of them, everything an ordinary ticket can name.
//
// Output → ../data/airports.js:  window.AIRPORTS = { "FRA": ["DE", "Frankfurt am Main"], … }
//
// Run: node fetch-airports.js         (weekly in the daily job; airports rarely change)

const fs = require("fs");
const path = require("path");
const fetch = require("node-fetch");

const URL = "https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv";
const OUT = path.join(__dirname, "..", "data", "airports.js");
const MIN_ROWS = 2500;   // a smaller result means the source changed shape: keep the old file

// Small CSV reader: quoted fields, doubled quotes, commas and newlines inside quotes.
function parseCsv(text) {
  const rows = []; let row = [], cur = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cur); cur = ""; }
    else if (c === "\n") { row.push(cur); rows.push(row); row = []; cur = ""; }
    else if (c !== "\r") cur += c;
  }
  if (cur || row.length) { row.push(cur); rows.push(row); }
  return rows;
}

(async () => {
  const r = await fetch(URL, { headers: { "User-Agent": "travelnow.info/1.0 (+https://travelnow.info)" } });
  if (!r.ok) throw new Error("HTTP " + r.status);
  const rows = parseCsv(await r.text());
  const head = rows.shift();
  const ix = Object.fromEntries(head.map((h, i) => [h, i]));
  for (const k of ["iata_code", "iso_country", "municipality", "name", "scheduled_service", "type"]) if (!(k in ix)) throw new Error("column missing: " + k);

  const rank = { large_airport: 3, medium_airport: 2, small_airport: 1 };
  const out = {};
  for (const c of rows) {
    const iata = (c[ix.iata_code] || "").trim().toUpperCase();
    if (!/^[A-Z]{3}$/.test(iata) || c[ix.scheduled_service] !== "yes" || !rank[c[ix.type]]) continue;
    const iso = (c[ix.iso_country] || "").trim().toUpperCase();
    if (!/^[A-Z]{2}$/.test(iso)) continue;
    const city = (c[ix.municipality] || c[ix.name] || "").trim();
    const prev = out[iata];
    if (!prev || rank[c[ix.type]] > prev.r) out[iata] = { r: rank[c[ix.type]], v: [iso, city] };
  }
  const codes = Object.keys(out).sort();
  if (codes.length < MIN_ROWS) throw new Error(`only ${codes.length} airports — keeping the previous file`);

  const body = "// AUTO-GENERATED by backend/fetch-airports.js — do not edit by hand.\n"
    + "// IATA code → [ISO2 country, city]. Source: OurAirports (public domain).\n"
    + "window.AIRPORTS = {\n" + codes.map((k) => ` ${JSON.stringify(k)}:${JSON.stringify(out[k].v)}`).join(",\n") + "\n};\n";
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${OUT}: ${codes.length} airports, ${(body.length / 1024).toFixed(0)} KB`);
})().catch((e) => { console.error(e.message); process.exit(1); });
