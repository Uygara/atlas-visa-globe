// fetch-british-classes.js — build sourced visa maps for British *nationality
// classes* (passport variants), which get markedly different visa treatment
// than a full British Citizen passport. Only classes with a dedicated,
// parseable Wikipedia "Visa requirements for …" table are emitted — we never
// invent data. BN(O), British subjects and British protected persons have NO
// such table, so they are deliberately omitted (see STATE.md).
//
// Output: data/passport-variants-gb.js  →  window.PASSPORT_VARIANTS_GB
//   { lastUpdated, <classKey>: { default, defaultDays, vf, ev, voa, vr, source } }
// passport-variants.js merges this under PASSPORT_VARIANTS.GB as `mode:"full"`
// variants (a full map with its OWN default, NOT an overlay on the ordinary GB
// map — a weaker class must not inherit the strong British-Citizen access).
//
// Run: node backend/fetch-british-classes.js

const fs = require("fs");
const path = require("path");
const { scrapePassport, buildPassportEntry, SOURCE_DIR } = require("./scraper");

const CLASSES = [
  { key: "botc",
    name: "British Overseas Territories citizen",
    title: "Visa_requirements_for_British_Overseas_Territories_citizens" },
  { key: "boc",
    name: "British Overseas citizen",
    title: "Visa_requirements_for_British_Overseas_citizens" },
];

(async () => {
  const out = { lastUpdated: new Date().toISOString().slice(0, 10) };
  for (const c of CLASSES) {
    process.stdout.write(`${c.name}… `);
    try {
      const scrape = await scrapePassport(c.name, null, c.title);
      if (scrape.rows.length < 50) {
        console.log(`✗ only ${scrape.rows.length} rows — skipped (page layout changed?)`);
        continue;
      }
      const [, entry] = buildPassportEntry(scrape);
      out[c.key] = {
        default: entry.default,
        defaultDays: entry.defaultDays || null,
        vf: entry.vf || [], ev: entry.ev || [], voa: entry.voa || [], vr: entry.vr || [],
        source: `https://en.wikipedia.org/wiki/${c.title}`,
      };
      const counts = { vf: 0, ev: 0, voa: 0, vr: 0 };
      scrape.rows.forEach(r => { if (counts[r.status] != null) counts[r.status]++; });
      console.log(`✓ ${scrape.rows.length} rows (default ${entry.default}; ${JSON.stringify(counts)})`);
    } catch (e) {
      console.log(`✗ ${e.message}`);
    }
    await new Promise(r => setTimeout(r, 1100));
  }

  const js =
    `// AUTO-GENERATED by backend/fetch-british-classes.js — do not edit by hand.\n` +
    `// Sourced visa maps for British nationality classes (BOTC / BOC). Merged into\n` +
    `// PASSPORT_VARIANTS.GB as full-map variants by data/passport-variants.js.\n` +
    `window.PASSPORT_VARIANTS_GB = ${JSON.stringify(out, null, 1)};\n`;
  fs.writeFileSync(path.join(SOURCE_DIR, "passport-variants-gb.js"), js);
  console.log(`\n✓ Wrote data/passport-variants-gb.js (${Object.keys(out).length - 1} classes)`);
})();
