// advisory-changes.js: build data/advisory-changes.js from data/advisory-history/.
//
//   node backend/advisory-changes.js
//
// Walks consecutive daily snapshots from the last 30 days and records every
// country-level advisory change (region changes are listed as names on the same
// entry). Output: window.ADVISORY_CHANGES = [{date, issuer, dest, from, to, regions}],
// newest first, max 300 entries. Empty while only one snapshot exists.

const fs = require("fs");
const path = require("path");
const { diffSnapshots } = require("./advisory-diff");

const DIR = path.join(__dirname, "..", "data", "advisory-history");
const OUT = path.join(__dirname, "..", "data", "advisory-changes.js");
const DAYS = 30, MAX = 300;

function build() {
  let dates = [];
  try { dates = fs.readdirSync(DIR).filter(f => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).map(f => f.slice(0, 10)).sort(); } catch (e) {}
  const cutoff = new Date(Date.now() - DAYS * 864e5).toISOString().slice(0, 10);
  // Keep one snapshot just before the window so the first in-window day has a baseline.
  const firstIn = dates.findIndex(d => d >= cutoff);
  const use = firstIn < 0 ? [] : dates.slice(Math.max(0, firstIn - 1));
  const out = [];
  for (let i = 1; i < use.length; i++) {
    const a = JSON.parse(fs.readFileSync(path.join(DIR, use[i - 1] + ".json"), "utf8"));
    const b = JSON.parse(fs.readFileSync(path.join(DIR, use[i] + ".json"), "utf8"));
    const byKey = new Map();
    for (const c of diffSnapshots(a, b)) {
      const k = c.issuer + "|" + c.iso;
      if (!byKey.has(k)) byKey.set(k, { date: use[i], issuer: c.issuer, dest: c.iso, from: null, to: null, regions: [] });
      const e = byKey.get(k);
      if (c.type === "level") { e.from = c.from; e.to = c.to; }
      else if (c.region && !e.regions.includes(c.region)) e.regions.push(c.region);
    }
    // Entries with no country-level change and no regions cannot occur; region-only ones keep from/to null.
    out.push(...byKey.values());
  }
  out.sort((x, y) => y.date.localeCompare(x.date));
  return out.slice(0, MAX);
}

const list = build();
const header = "// Generated by backend/advisory-changes.js from data/advisory-history/. Do not edit by hand.\n";
fs.writeFileSync(OUT, header + "window.ADVISORY_CHANGES = " + JSON.stringify(list) + ";\n");
console.log("advisory-changes: " + list.length + " entries");
